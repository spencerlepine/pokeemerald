def grid(kind: str, size: str):
    rows = [r for r in GRIDS[kind][size].strip().splitlines()]
    h, w = len(rows), max(len(r) for r in rows)
    out = [[False] * 16 for _ in range(16)]
    oy, ox = (16 - h) // 2, (16 - w) // 2
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == "#":
                out[oy + y][ox + x] = True
    return out

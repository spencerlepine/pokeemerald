SMALL["@"] = [".####.", "#.##.#", "##...#", "##...#", "#.##.#", ".####."]  # copyright sign


def small_mask(text, spacing=1):
    w = sum(len(SMALL[c][0]) for c in text) + spacing * (len(text) - 1)
    img = Image.new("L", (max(1, w), 6), 0)
    px = img.load()
    x = 0
    for ch in text:
        g = SMALL[ch]
        for r, row in enumerate(g):
            for c, v in enumerate(row):
                if v == "#":
                    px[x + c, r] = 255
        x += len(g[0]) + spacing
    return img

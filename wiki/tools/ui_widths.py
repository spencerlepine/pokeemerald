#!/usr/bin/env python3
"""List C-side UI strings whose Star Wars text is wider than Emerald's (writes progress/UI_WIDTH_REVIEW.md).

Dialogue boxes are checked by the build (overflow_risk). Menu and screen strings live in fixed or
auto-sized windows that only the game code knows, so this list is the hand-off for Step 4: each row
either fits an auto-sized menu (no change), needs its window widened, or needs a shorter text.
"""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import build  # noqa: E402

UI_FILES = ("src/strings.c", "src/battle_message.c", "src/text_input_strings.c", "src/landmark.c",
            "src/data/text/gift_ribbon_descriptions.h", "src/data/union_room.h", "src/data/credits.h")


def width(t):
    return max(build.line_px(x) for x in re.split(r"\\[nlp]", t))


rows = []
for r in csv.DictReader(open(ROOT / "database" / "texts.csv", encoding="utf-8")):
    if r["source_file"] in UI_FILES or r["source_file"].startswith("src/") and r["text_context"] != "dialogue":
        o, n = width(r["emerald_text_raw"]), width(r["sw_text_raw"])
        if n > o:
            rows.append((n - o, o, n, r["text_id"], r["source_file"], r["emerald_text_raw"], r["sw_text_raw"]))
rows.sort(reverse=True)
out = ["# UI width review", "", "Generated by `python3 tools/ui_widths.py`; do not edit by hand.", "",
       f"{len(rows)} menu/screen strings are wider than Emerald's original. Auto-sized menus (multichoice, "
       "PC menu) absorb this; fixed windows need a resize in Step 4 or a shorter text here.", "",
       "| +px | Emerald px | Star Wars px | Text id | File | Emerald | Star Wars |", "|---:|---:|---:|---|---|---|---|"]
for d, o, n, tid, f, e, s in rows:
    esc = lambda t: t.replace("|", "\\|")
    out.append(f"| {d} | {o} | {n} | `{tid}` | {f} | {esc(e)} | {esc(s)} |")
(ROOT / "progress" / "UI_WIDTH_REVIEW.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(len(rows), "rows -> progress/UI_WIDTH_REVIEW.md")

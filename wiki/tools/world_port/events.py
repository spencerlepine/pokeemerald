"""The events of every ported map: people, signs and their scripts.

  vanilla and hybrid maps  keep every vanilla object, trigger and sign. An object whose cell the wiki has
                           made solid (a building placed over it) moves to the nearest open cell. People the
                           wiki adds (a yaml person with no vanilla object on its cell) become new objects.
  new maps                 every yaml person is a new object, every yaml sign a new sign.
  redrawn vanilla maps     towns.py (their vanilla events are moved by hand-checked rules).

A new person's script comes from its row in mapping/people.csv (matched by area, yaml name and index):
lines, trainer, boss, wild battle and flag. The generated scripts and texts go in a managed block of the
map's scripts.inc (between `@ world_port begin` and `@ world_port end`). A label of the same name written by
hand outside the block wins: the block then leaves that script out, so a person's script can be replaced.
"""
import re
import sys
from collections import Counter, defaultdict

from . import base as B, model as M

BEGIN, END = "@ world_port begin (generated by wiki/tools/world_port, do not edit inside)\n", "@ world_port end\n"
WALKABLE = set('.:"=H_')


def _port_people():
    sys.path.insert(0, str(B.WIKI / "tools"))
    import port_people as PP
    return PP


_GFX = None


def gfx_consts():
    global _GFX
    if _GFX is None:
        t = (B.GAME / "include/constants/event_objects.h").read_text()
        _GFX = set(re.findall(r"#define (OBJ_EVENT_GFX_\w+)", t))
    return _GFX


def gfx_const(walker, role="npc"):
    if walker.startswith("object-gfx:"):
        c = "OBJ_EVENT_GFX_" + walker.split(":", 1)[1].upper().replace("-", "_")
    elif walker.startswith("net:walker-"):
        new = {r["id"]: r for r in M.read_csv(B.MAPPING / "new_people.csv")}
        c = new.get(walker, {}).get("constant", "")
    else:
        c = ""
    if c in gfx_consts():
        return c
    return {"trainer": "OBJ_EVENT_GFX_HIKER", "story": "OBJ_EVENT_GFX_MAN_3"}.get(role, "OBJ_EVENT_GFX_MAN_1")


def flag_const(tok):
    if not tok:
        return None
    if tok.startswith("flag:unused-"):
        return "FLAG_UNUSED_0x" + tok.split("unused-", 1)[1][2:].upper()
    if tok.startswith("flag:"):
        return "FLAG_" + tok.split(":", 1)[1].upper().replace("-", "_")
    return None


def people_rows():
    rows = defaultdict(list)
    for r in M.read_csv(B.MAPPING / "people.csv"):
        rows[r["area"]].append(r)
    return rows


def row_for(rows, area, person, nth):
    for r in rows.get(area.id, []):
        if r["yaml_name"] == person["name"] and (r["yaml_index"] in ("", str(nth))):
            return r
    return None


def key_of(name, nth, multi):
    k = "".join(p.capitalize() for p in re.split(r"[^A-Za-z0-9]+", name) if p) or "Person"
    return f"{k}{nth}" if multi else k


def nearest_open(area, coll, x, y, taken):
    best = None
    for yy in range(area.h):
        for xx in range(area.w):
            if coll[yy, xx] == 0 and (xx, yy) not in taken and area.grid[yy][xx] in WALKABLE:
                d = abs(xx - x) + abs(yy - y)
                if best is None or d < best[0]:
                    best = (d, xx, yy)
    return (best[1], best[2]) if best else (x, y)


def species_level(tok):
    m = re.match(r"species:([\w-]+)@(\d+)", tok)
    return ("SPECIES_" + m.group(1).upper().replace("-", "_"), int(m.group(2))) if m else None


class Block:
    """The generated scripts and texts of one map."""

    def __init__(self, map_name, existing):
        self.m = map_name
        self.existing = existing          # labels already in the map's scripts.inc outside the block
        self.scripts, self.texts = [], []
        self.text_labels = set()

    def label(self, kind, key):
        return f"{self.m}_{kind}_Sw{key}"

    def text(self, key, i, line):
        PP = _port_people()
        lab = f"{self.m}_Text_Sw{key}_{i}"
        if lab not in self.text_labels and lab not in self.existing:
            self.text_labels.add(lab)
            self.texts.append(f"{lab}:\n{PP.asm_string(PP.wrap(line))}\n")
        return lab

    def script(self, label, body):
        if label in self.existing:
            return label
        self.scripts.append(f"{label}::\n{body}\n")
        return label

    def render(self):
        return BEGIN + "".join(self.scripts) + "".join(self.texts) + END


# Supply Depot stock by the badges the player holds on reaching the planet (vanilla marts of the same stage).
MART_STOCK = [
    (0, "POKE_BALL POTION ANTIDOTE PARALYZE_HEAL AWAKENING ESCAPE_ROPE REPEL X_SPEED X_ATTACK X_DEFEND"),
    (2, "POKE_BALL GREAT_BALL POTION SUPER_POTION ANTIDOTE PARALYZE_HEAL AWAKENING ESCAPE_ROPE REPEL X_SPEED X_ATTACK "
        "X_DEFEND"),
    (5, "GREAT_BALL ULTRA_BALL SUPER_POTION HYPER_POTION FULL_HEAL REVIVE SUPER_REPEL ESCAPE_ROPE X_ATTACK X_DEFEND"),
    (7, "ULTRA_BALL HYPER_POTION MAX_POTION FULL_HEAL REVIVE MAX_REPEL ESCAPE_ROPE X_ATTACK X_DEFEND"),
]
_BADGES = None
SERVICE_CHARACTERS = ("character:mart-clerk", "character:pokemon-center-nurse")


def planet_badges(planet):
    global _BADGES
    if _BADGES is None:
        _BADGES = {r["planet"]: int(r["arrive_badges"] or 0) for r in M.read_csv(B.MAPPING / "planets.csv")}
    return _BADGES.get(planet, 0)


def mart_items(row, area):
    """A clerk's stock: `item:<name>` tokens in the row's party column, else the stage's vanilla list."""
    toks = [x for x in (row.get("party") or "").split("|") if x.startswith("item:")]
    if toks:
        return ["ITEM_" + x.split(":", 1)[1].upper().replace("-", "_") for x in toks]
    stock = [s for b, s in MART_STOCK if b <= planet_badges(area.planet)][-1]
    return ["ITEM_" + x for x in stock.split()]


def person_script(blk, key, row, display, area):
    """As _person_script; a `flag` of `hide:FLAG_X` is the object's flag instead (the person is there until the
    story sets FLAG_X, like a road warden), and the script does not set it."""
    if row and (row.get("flag") or "").startswith("hide:"):
        hide = row["flag"][5:]
        label, trainer, _ = _person_script(blk, key, dict(row, flag=""), display, area)
        return label, trainer, hide
    return _person_script(blk, key, row, display, area)


def _person_script(blk, key, row, display, area):
    """The script of one new person; returns (label, trainer fields, object flag).

    A row whose character is the mart clerk runs a Supply Depot (stock from mart_items); the Bacta Center nurse heals
    (Common_EventScript_PkmnCenterNurse, facing the player by VAR_LAST_TALKED)."""
    PP = _port_people()
    label = blk.label("EventScript", key)
    ch = (row or {}).get("character", "")
    if ch == "character:mart-clerk":
        items = mart_items(row, area)
        blk.script(label, f"\tlock\n\tfaceplayer\n\tmessage gText_HowMayIServeYou\n\twaitmessage\n"
                          f"\tpokemart {label}_Stock\n\tmsgbox gText_PleaseComeAgain, MSGBOX_DEFAULT\n\trelease\n\tend\n\n"
                          f"\t.align 2\n{label}_Stock:\n" + "".join(f"\t.2byte {i}\n" for i in items)
                   + "\tpokemartlistend\n")
        return label, False, None
    if ch == "character:pokemon-center-nurse":
        blk.script(label, "\tcopyvar VAR_0x800B, VAR_LAST_TALKED\n\tcall Common_EventScript_PkmnCenterNurse\n"
                          "\twaitmessage\n\twaitbuttonpress\n\trelease\n\tend\n")
        return label, False, None
    lines = PP.split_lines(row["lines"]) if row and row["lines"] else []
    label = blk.label("EventScript", key)
    flag = flag_const(row["flag"]) if row else None
    kind = row["kind"] if row else "npc"
    if not lines:
        lines = [f"{display}"]
    t = [blk.text(key, i, ln) for i, ln in enumerate(lines, 1)]
    if kind in ("trainer", "boss") and row.get("trainer_const"):
        intro, lose = t[0], (t[1] if len(t) > 1 else t[0])
        after = t[2] if len(t) > 2 else lose
        body = f"\ttrainerbattle_single {row['trainer_const']}, {intro}, {lose}"
        if flag:
            body += f", {label}_Won\n"
            blk.script(label + "_Won", f"\tsetflag {flag}\n\trelease\n\tend\n")
        else:
            body += "\n"
        body += f"\tmsgbox {after}, MSGBOX_AUTOCLOSE\n\tend\n"
        blk.script(label, body)
        return label, kind == "trainer", None
    if kind == "wild":
        sp = species_level((row.get("party") or "").split("|")[0])
        body = "\tlock\n\tfaceplayer\n" + "".join(f"\tmsgbox {x}, MSGBOX_DEFAULT\n" for x in t)
        if sp:
            body += f"\tsetwildbattle {sp[0]}, {sp[1]}\n\tdowildbattle\n"
        if flag:
            body += f"\tsetflag {flag}\n"
        body += "\tremoveobject VAR_LAST_TALKED\n\trelease\n\tend\n" if flag else "\trelease\n\tend\n"
        blk.script(label, body)
        return label, False, flag
    body = "\tlock\n\tfaceplayer\n" + "".join(f"\tmsgbox {x}, MSGBOX_DEFAULT\n" for x in t)
    if flag:
        body += f"\tsetflag {flag}\n"
    body += "\trelease\n\tend\n"
    blk.script(label, body)
    return label, False, None


def new_object(area, C, p, row, label, trainer, flag, taken, problems):
    x, y = p["at"]
    if not (0 <= x < area.w and 0 <= y < area.h) or C.coll[y, x] or area.grid[y][x] not in WALKABLE:
        nx, ny = nearest_open(area, C.coll, x, y, taken)
        problems.append(f"{area.id}: {p['name']} at ({x},{y}) is on a solid cell; moved to ({nx},{ny})")
        x, y = nx, ny
    taken.add((x, y))
    role = p.get("role", "npc")
    walker = (row or {}).get("walker", "")
    if trainer:
        move, sight, ttype = "MOVEMENT_TYPE_LOOK_AROUND", "3", "TRAINER_TYPE_NORMAL"
    elif role == "townsfolk":
        move, sight, ttype = "MOVEMENT_TYPE_WANDER_AROUND", "0", "TRAINER_TYPE_NONE"
    else:
        move, sight, ttype = "MOVEMENT_TYPE_FACE_DOWN", "0", "TRAINER_TYPE_NONE"
    return {"graphics_id": gfx_const(walker, role), "x": x, "y": y, "elevation": int(C.elev[y, x]) or 3,
            "movement_type": move, "movement_range_x": 1, "movement_range_y": 1, "trainer_type": ttype,
            "trainer_sight_or_berry_tree_id": sight, "script": label, "flag": flag or "0"}


def existing_labels(path):
    if not path.exists():
        return set(), ""
    t = path.read_text()
    if BEGIN in t:
        outside = t[:t.index(BEGIN)] + t[t.index(END) + len(END):]
    else:
        outside = t
    return set(re.findall(r"^(\w+)::?", outside, re.M)), outside


def write_block(path, blk, header=None):
    _, outside = existing_labels(path)
    if not outside.strip() and header:
        outside = header
    t = outside.rstrip("\n") + "\n\n" + blk.render() if blk.scripts or blk.texts else outside
    B.write_text(path, t)


SIMPLE_CMDS = {"lock", "lockall", "faceplayer", "msgbox", "release", "releaseall", "end", "applywaitmovement",
               "waitmovement", "closemessage"}


def map_slug(map_name):
    return re.sub(r"(?<=[a-z])(?=[A-Z])|_", "-", map_name).lower().replace("--", "-")


def vanilla_body(map_name, label):
    path = B.BASE_GAME / "data/maps" / map_name / "scripts.inc"
    if not path.exists():
        return None
    body, on = [], False
    for line in path.read_text().splitlines():
        if line.startswith(label + "::") or line.startswith(label + ":"):
            on = True
            continue
        if on:
            if re.match(r"^\w+::?", line):
                break
            if line.strip():
                body.append(line.strip().split()[0])
    return body if on else None


def apply_takeovers(a, objs, blk, rows, problems):
    """A people.csv row with npc_id npc:<vanilla map>:<n> takes over vanilla object n: its walker, and its lines
    when the vanilla script only talks (one that gives, sets or branches keeps its script)."""
    slug = map_slug(a.map_name)
    for row in rows.get(a.id, []):
        nid = row.get("npc_id", "")
        if not nid.startswith("npc:"):
            continue
        _, m, n = nid.split(":")
        if m != slug or not n.isdigit() or not (1 <= int(n) <= len(objs)):
            problems.append(f"{a.id}: takeover {row['person_id']} names {nid}, not an object of {a.map_name}")
            continue
        o = objs[int(n) - 1]
        if row.get("walker"):
            o["graphics_id"] = gfx_const(row["walker"], row.get("kind", "npc"))
        body = vanilla_body(a.map_name, o.get("script", ""))
        if body and set(body) <= SIMPLE_CMDS and row.get("lines"):
            who = (row.get("character") or "").split(":")[-1].replace("character-", "")
            key = "".join(w.capitalize() for w in re.split(r"[^A-Za-z0-9]+", who) if w) or f"Takeover{n}"
            label, _, _ = person_script(blk, key, row, who.upper(), a)
            o["script"] = label
        elif row.get("lines"):
            problems.append(f"{a.id}: {row['person_id']} takes over {o.get('script')}, which does more than talk; "
                            f"walker changed, vanilla script kept")


def events(world, a, r, mj):
    """Fill mj's object, sign and trigger events for a vanilla, hybrid or new map; returns problems."""
    problems = []
    C = r["C"]
    rows = world.people_rows
    path = B.GAME / "data/maps" / a.map_name / "scripts.inc"
    labels, _ = existing_labels(path)
    blk = Block(a.map_name, labels)
    objs = mj.get("object_events") or []
    taken = set()
    if not a.new:
        # vanilla objects stay; one the wiki walled in moves out
        for o in objs:
            x, y = o["x"], o["y"]
            # (people a script places, with no script of their own, stay: the script walks them)
            if (0 <= x < a.w and 0 <= y < a.h and C.coll[y, x] and (x, y) in r["piece_cells"]
                    and o.get("script") not in ("0x0", "0")):
                nx, ny = nearest_open(a, C.coll, x, y, taken | {(q["x"], q["y"]) for q in objs})
                problems.append(f"{a.id}: vanilla object {o.get('script')} at ({x},{y}) is under a new piece; "
                                f"moved to ({nx},{ny})")
                o["x"], o["y"] = nx, ny
            taken.add((o["x"], o["y"]))
    vpos = Counter((o["x"], o["y"]) for o in objs) if not a.new else Counter()
    counts = Counter(p["name"] for p in a.people)
    seen = Counter()
    for p in a.people:
        seen[p["name"]] += 1
        nth = seen[p["name"]]
        if vpos[tuple(p["at"])]:
            vpos[tuple(p["at"])] -= 1
            continue
        row = row_for(rows, a, p, nth)
        if p["name"] == "Pilot" and world.lanes.has_pilot(a):
            label = world.lanes.pilot_script(blk, a, key_of(p["name"], nth, counts[p["name"]] > 1))
            objs.append(new_object(a, C, p, row, label, False, None, taken, problems))
            continue
        if not a.new and not row:
            problems.append(f"{a.id}: {p['name']} at {p['at']} has no vanilla object and no people.csv row; left out")
            continue
        if row and not row["lines"] and row["kind"] not in ("wild",) and row.get("character") not in SERVICE_CHARACTERS:
            problems.append(f"{a.id}: {p['name']} has no lines in people.csv; says their name")
        if not row:
            problems.append(f"{a.id}: {p['name']} has no people.csv row; says their name")
        key = key_of(p["name"], nth, counts[p["name"]] > 1)
        label, trainer, flag = person_script(blk, key, row, p["name"].upper(), a)
        objs.append(new_object(a, C, p, row, label, trainer, flag, taken, problems))
    if not a.new:
        apply_takeovers(a, objs, blk, rows, problems)
    if len(objs) > 64:
        problems.append(f"{a.id}: {len(objs)} objects, the game holds 64; the last ones are left out")
        objs = objs[:64]
    mj["object_events"] = objs
    if a.new:
        bgs = []
        for i, s in enumerate(a.signs, 1):
            x, y = s["at"]
            key = key_of(s.get("name", "Sign"), i, True)
            t = blk.text(key, 1, f"{a.name.upper()}: {s.get('name', 'sign')}")
            lab = blk.script(blk.label("EventScript", key), f"\tmsgbox {t}, MSGBOX_SIGN\n\tend\n")
            bgs.append({"type": "sign", "x": x, "y": y, "elevation": 0,
                        "player_facing_dir": "BG_EVENT_PLAYER_FACING_ANY", "script": lab})
        mj["bg_events"] = bgs
        header = f"{a.map_name}_MapScripts::\n\t.byte 0\n"
        if a.id in world.lanes.shared:
            header = world.lanes.cabin_map_scripts(a)
            mj["coord_events"] = world.lanes.cabin_triggers(blk, a)
        if f"{a.map_name}_MapScripts" not in labels:
            blk.scripts.insert(0, header + "\n")
        write_block(path, blk)
    else:
        write_block(path, blk)
    return problems
